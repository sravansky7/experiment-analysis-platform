
import hashlib
import json
from datetime import datetime, timezone

import pandas as pd

from src.config import (
    RANDOM_SEED,
    DATASET_MODE,
    RAW_DATA_DIR,
    OUTPUT_DIR,
    get_user_count,
)


DATASETS = {
    "experiments": "experiments.csv",
    "variants": "variants.csv",
    "audience_members": "audience_members.csv",
    "assignments": "assignments.csv",
    "exposure_events": "exposure_events.csv",
    "conversion_events": "conversion_events.csv",
    "guardrail_events": "guardrail_events.csv"
}


def calculate_sha256(file_path):
    """Calculate the SHA-256 checksum of a file."""
    digest = hashlib.sha256()

    with open(file_path, "rb") as file:
        for chunk in iter(lambda: file.read(1024 * 1024), b""):
            digest.update(chunk)

    return digest.hexdigest()


def create_manifest():
    """Create a traceable manifest for generated source datasets."""
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)

    manifest = {
        "project": "Experiment Analysis Platform",
        "dataset_type": "synthetic",
        "generated_at_utc": datetime.now(timezone.utc).isoformat(),
        "random_seed": RANDOM_SEED,
        "dataset_mode": DATASET_MODE,
        "configured_user_count": get_user_count(),
        "datasets": [],
    }

    for dataset_name, filename in DATASETS.items():
        file_path = RAW_DATA_DIR / filename

        if not file_path.exists():
            raise FileNotFoundError(
                f"Dataset missing: {file_path}. "
                "Generate the datasets before creating the manifest."
            )

        dataframe = pd.read_csv(file_path)

        manifest["datasets"].append({
            "dataset_name": dataset_name,
            "file_name": filename,
            "relative_path": f"data/raw/{filename}",
            "format": "CSV",
            "record_count": len(dataframe),
            "columns": list(dataframe.columns),
            "file_size_bytes": file_path.stat().st_size,
            "sha256": calculate_sha256(file_path),
            "source": "Synthetic data generated by the project pipeline",
        })

    manifest_path = OUTPUT_DIR / "source_manifest.json"

    with open(manifest_path, "w", encoding="utf-8") as file:
        json.dump(manifest, file, indent=2, ensure_ascii=False)

    print("\n===== SOURCE MANIFEST =====")
    print(f"Datasets documented: {len(manifest['datasets'])}")
    print(f"Random seed: {RANDOM_SEED}")
    print(f"Dataset mode: {DATASET_MODE}")
    print(f"Manifest saved: {manifest_path}")

    for dataset in manifest["datasets"]:
        print(
            f"{dataset['dataset_name']}: "
            f"{dataset['record_count']} records"
        )

    return manifest


if __name__ == "__main__":
    create_manifest()
